"""Parse and validate knowledge/experiments/*.md (structured experiment / dead-end records).

An experiment record is a markdown file whose front matter carries the short, filterable fields and whose body has a fixed
set of sections (see templates/experiment.md in the gamedecomp-library skill). Failed and partial results are first-class:
they must say why and what to try next. Used by build_knowledge.py; also runnable alone for a quick lint.
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
from index_local_notes import parse, sections, lint, clip
import rgraph

BASE = 'https://github.com/madpai/game-decomp-compendium/blob/main/knowledge/experiments/'
REQUIRED = ('id', 'title', 'project', 'result', 'level', 'why_level', 'scope', 'date', 'agents', 'about')
SECTIONS = ('Symptom', 'Hypothesis', 'Environment', 'Change', 'Oracle', 'Result', 'Why', 'Next', 'Unverified')
ID_RE = re.compile(r'^EXP-[A-Z0-9]{2,8}-\d{3}$')


def collect(repo_root):
    d = os.path.join(repo_root, 'knowledge', 'experiments')
    recs, bad = [], []
    if not os.path.isdir(d): return recs, bad
    for f in sorted(os.listdir(d)):
        if not f.endswith('.md') or f in ('README.md', 'INDEX.md', 'TEMPLATE.md'): continue
        text = open(os.path.join(d, f), encoding='utf-8').read()
        fm, body = parse(text)
        if fm is None: bad.append(f'experiments/{f}: no front matter'); continue
        tag = f'experiments/{f}'
        for k in REQUIRED:
            if not fm.get(k): bad.append(f'{tag}: missing {k}')
        eid = fm.get('id', '')
        if not ID_RE.match(eid): bad.append(f'{tag}: id {eid!r} must look like EXP-OO-001')
        if not f.startswith(eid.lower() + '-'): bad.append(f'{tag}: file name must start with {eid.lower()}-')
        if fm.get('result') not in rgraph.RESULTS: bad.append(f'{tag}: result must be one of {rgraph.RESULTS}')
        for k in ('level', 'why_level'):
            if fm.get(k) not in rgraph.LEVELS: bad.append(f'{tag}: {k} must be one of {rgraph.LEVELS}')
        if fm.get('scope') not in rgraph.SCOPES: bad.append(f'{tag}: scope must be one of {rgraph.SCOPES}')
        if fm.get('scope') == 'family': bad.append(f'{tag}: an experiment is one project\'s run; use scope build or project (family claims belong in findings with confirmed_by)')
        for k in ('about', 'related', 'games'):
            if k in fm and not isinstance(fm[k], list): bad.append(f'{tag}: {k} must be a list')
        sec = sections(body)
        for s in SECTIONS:
            if len(sec.get(s, '')) < 20: bad.append(f'{tag}: section "## {s}" missing or too short')
        if fm.get('result') in ('failed', 'partial'):
            if len(sec.get('Why', '')) < 60: bad.append(f'{tag}: a {fm["result"]} result must explain why (section Why, 60+ chars)')
            if len(sec.get('Next', '')) < 30: bad.append(f'{tag}: a {fm["result"]} result must give a next direction')
        bad += lint(tag, text)
        recs.append({
            'id': eid, 'title': fm.get('title', ''), 'project': fm.get('project', ''), 'result': fm.get('result'), 'level': fm.get('level'),
            'why_level': fm.get('why_level'), 'scope': fm.get('scope'), 'status': fm.get('status', 'final'), 'date': fm.get('date'),
            'agents': fm.get('agents', []), 'about': fm.get('about', []), 'games': fm.get('games', []), 'tags': fm.get('tags', []),
            'related': fm.get('related', []), 'supersedes': fm.get('supersedes', ''), 'path': 'experiments/' + f, 'url': BASE + f,
            'sections': {s: sec.get(s, '') for s in SECTIONS}})
    ids = [r['id'] for r in recs]
    for i in set(ids):
        if ids.count(i) > 1: bad.append(f'duplicate experiment id {i}')
    for r in recs:
        for x in list(r['related']) + ([r['supersedes']] if r['supersedes'] else []):
            if x not in ids: bad.append(f"{r['path']}: related/supersedes unknown experiment {x}")
    recs.sort(key=lambda r: r['id'])
    return recs, bad


def render_index(recs):
    lines = ['# Experiments and dead ends', '', '_Generated by `skills/gamedecomp-library/scripts/refresh/build_knowledge.py`; do not edit by hand._', '',
             'Find one with `hub.py tried "<idea>"` or `hub.py experiments --result failed`. Format and rules: [README](README.md).', '',
             '| ID | Result | Evidence (result / cause) | Project | Title |', '|---|---|---|---|---|']
    for r in recs:
        lines.append(f"| [{r['id']}]({os.path.basename(r['path'])}) | {r['result']} | {r['level']} / {r['why_level']} | {r['project']} | {r['title']} |")
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    root = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', '..'))
    r, b = collect(root)
    print(f'{len(r)} experiments', ('; PROBLEMS:\n  ' + '\n  '.join(b)) if b else '')
    sys.exit(1 if b else 0)
